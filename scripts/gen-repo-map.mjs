// Generates docs/REPO-MAP.md: every source file with its line count and exported names (test files list
// their top-level describe blocks). One cheap read replaces many greps. Run with: npm run docs:map
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const ROOTS = ['src', 'e2e', 'scripts'];
const MAX_NAMES = 14;

async function walk(dir) {
  const out = [];
  for (const entry of await readdir(path.join(root, dir), { withFileTypes: true })) {
    const rel = `${dir}/${entry.name}`;
    if (entry.isDirectory()) {
      if (entry.name === 'screenshots' || entry.name === 'node_modules') continue;
      out.push(...(await walk(rel)));
    } else if (/\.(ts|mjs)$/.test(entry.name) && !entry.name.endsWith('.d.ts')) {
      out.push(rel);
    }
  }
  return out;
}

function exportsOf(text) {
  const names = new Set();
  for (const m of text.matchAll(
    /^export\s+(?:default\s+)?(?:declare\s+)?(?:abstract\s+)?(?:async\s+)?(?:function\*?|class|const|let|type|interface|enum)\s+([A-Za-z0-9_$]+)/gm,
  ))
    names.add(m[1]);
  for (const m of text.matchAll(/^export\s*\{([^}]*)\}/gm))
    for (const part of m[1].split(',')) {
      const name = part
        .trim()
        .split(/\s+as\s+/)
        .pop();
      if (name) names.add(name);
    }
  return [...names];
}

function describesOf(text) {
  return [...text.matchAll(/^(?:test\.)?describe\((['"`])(.*?)\1/gm)].map((m) => m[2]);
}

function summarize(list) {
  if (list.length <= MAX_NAMES) return list.join(', ');
  return `${list.slice(0, MAX_NAMES).join(', ')}, +${list.length - MAX_NAMES} more`;
}

const files = [];
for (const dir of ROOTS) files.push(...(await walk(dir)));
files.sort();

const byFolder = new Map();
for (const file of files) {
  const text = await readFile(path.join(root, file), 'utf8');
  const lines = text.split('\n').length - (text.endsWith('\n') ? 1 : 0);
  const isTest = /\.(test|spec)\.ts$/.test(file);
  const detail = isTest ? summarize(describesOf(text)) : summarize(exportsOf(text));
  const folder = path.posix.dirname(file);
  if (!byFolder.has(folder)) byFolder.set(folder, []);
  byFolder.get(folder).push({ name: path.posix.basename(file), lines, detail, isTest });
}

const out = [];
out.push('# Repo map');
out.push('');
out.push(
  '> Generated by `npm run docs:map`. Do not edit by hand; regenerate after adding, removing or renaming files. Lines / exported names (tests: describe blocks).',
);
for (const [folder, entries] of byFolder) {
  out.push('');
  out.push(`## ${folder}/`);
  out.push('');
  for (const e of entries)
    out.push(`- \`${e.name}\` (${e.lines})${e.detail ? `: ${e.detail}` : ''}`);
}
out.push('');

await writeFile(path.join(root, 'docs', 'REPO-MAP.md'), out.join('\n'), 'utf8');
console.log(`docs/REPO-MAP.md: ${files.length} files`);
